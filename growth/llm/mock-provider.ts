import type { LLMProvider } from "./provider";
import type { EvidenceEntry, GrowthReportAnalysis, GrowthReportLLMRequest, LLMStructuredResult } from "../types/growth-report";

function findEvidence(catalog: EvidenceEntry[], id: string): EvidenceEntry | undefined {
  return catalog.find((entry) => entry.id === id);
}

function existingIds(catalog: EvidenceEntry[], ids: string[]): string[] {
  const catalogIds = new Set(catalog.map((entry) => entry.id));
  return ids.filter((id) => catalogIds.has(id));
}

/**
 * A fixed-logic (no LLM) implementation of LLMProvider used for local
 * end-to-end testing without an API key or network access. It only ever
 * cites evidence IDs it finds in the supplied catalog — never a hardcoded
 * ID that might not exist for a given period's data — so it works
 * unmodified against empty Search Console periods, missing product
 * conversions, or a period with no CTA activity at all.
 */
export class MockGrowthReportProvider implements LLMProvider {
  readonly name = "mock";

  async generateStructuredReport(request: GrowthReportLLMRequest): Promise<LLMStructuredResult<GrowthReportAnalysis>> {
    const { evidenceCatalog: catalog } = request;

    const searchStatus = findEvidence(catalog, "search.status")?.value ?? "missing";
    const sessions = findEvidence(catalog, "traffic.sessions")?.value ?? 0;
    const pageViews = findEvidence(catalog, "behavior.page_views")?.value ?? 0;

    const findings: GrowthReportAnalysis["findings"] = [];

    const trafficRefs = existingIds(catalog, ["traffic.sessions", "traffic.screen_page_views", "traffic.engaged_sessions"]);
    const screenPageViews = findEvidence(catalog, "traffic.screen_page_views")?.value ?? 0;
    if (trafficRefs.length > 0) {
      findings.push({
        id: "finding_traffic_overview",
        category: "traffic",
        title: "GA4 traffic overview for the period",
        observation: `GA4 recorded ${sessions} sessions and ${screenPageViews} screen/page views during the selected period, per the evidence catalog.`,
        interpretation: "This is a mock-generated placeholder observation for local pipeline testing, not a strategic analysis.",
        evidenceRefs: trafficRefs,
        confidence: "low",
        caveats: ["Generated by the Mock Provider — not a real analysis."],
      });
    }

    const ctaRefs = existingIds(catalog, ["behavior.page_views", "behavior.total_cta_clicks", "behavior.event_based_cta_rate"]);
    if (ctaRefs.length > 0) {
      findings.push({
        id: "finding_cta_behavior",
        category: "cta_behavior",
        title: "Growth-site CTA event counts",
        observation: `PostHog recorded ${pageViews} pageviews and a total CTA click count captured in the evidence catalog.`,
        interpretation:
          "This reflects event counts only, not a user or session conversion rate. This is a mock-generated placeholder for local pipeline testing.",
        evidenceRefs: ctaRefs,
        confidence: "low",
        caveats: ["Generated by the Mock Provider — not a real analysis."],
      });
    }

    const searchRefs = existingIds(catalog, ["search.status", "search.clicks", "search.impressions"]);
    if (searchRefs.length > 0) {
      const searchObservation =
        searchStatus === "ok"
          ? "Search Console returned search-performance data for this period, per the evidence catalog."
          : searchStatus === "empty"
            ? "Search Console's API connection succeeded, but all search-performance reports returned zero rows for this period."
            : "No Search Console snapshot was available for this period.";
      findings.push({
        id: "finding_search_status",
        category: "search",
        title: "Search Console data availability",
        observation: searchObservation,
        interpretation: "This is a mock-generated placeholder observation for local pipeline testing, not a strategic analysis.",
        evidenceRefs: searchRefs,
        confidence: "low",
        caveats: ["Generated by the Mock Provider — not a real analysis."],
      });
    }

    const dataQualityRefs = existingIds(catalog, ["data_quality.overall_status", "data_quality.product_conversions"]);
    if (dataQualityRefs.length > 0) {
      findings.push({
        id: "finding_data_quality",
        category: "data_quality",
        title: "Data-quality status for this report",
        observation: "The evidence catalog's data-quality entries describe the current measurement limitations for this period.",
        interpretation: "This is a mock-generated placeholder observation for local pipeline testing, not a strategic analysis.",
        evidenceRefs: dataQualityRefs,
        confidence: "low",
        caveats: ["Generated by the Mock Provider — not a real analysis."],
      });
    }

    if (findings.length === 0) {
      // Every real evidence catalog always includes at least the data-quality
      // entries, but stay defensive: the schema requires 1-8 findings.
      findings.push({
        id: "finding_no_evidence",
        category: "data_quality",
        title: "No evidence available",
        observation: "The supplied evidence catalog was empty for this period.",
        interpretation: "This is a mock-generated placeholder observation for local pipeline testing, not a strategic analysis.",
        evidenceRefs: existingIds(catalog, catalog.map((entry) => entry.id)).slice(0, 1),
        confidence: "low",
        caveats: ["Generated by the Mock Provider — not a real analysis."],
      });
    }

    const funnelObservations: GrowthReportAnalysis["funnelObservations"] = [];
    const funnelRefs = existingIds(catalog, ["behavior.page_views", "behavior.total_cta_clicks", "behavior.event_based_cta_rate"]);
    if (funnelRefs.length > 0) {
      funnelObservations.push({
        stage: "growth_site_cta",
        observation: "PostHog event counts for the growth-site funnel are captured in the referenced evidence.",
        evidenceRefs: funnelRefs,
        confidence: "low",
      });
    }

    const channelAndContentObservations: GrowthReportAnalysis["channelAndContentObservations"] = [];
    const topChannelRefs = existingIds(catalog, ["traffic.top_source.1", "traffic.top_landing_page.1"]);
    if (topChannelRefs.length > 0) {
      channelAndContentObservations.push({
        title: "Top channel/content signal",
        observation: "The referenced evidence entries identify the top-performing source and/or landing page for this period.",
        evidenceRefs: topChannelRefs,
        confidence: "low",
        caveats: ["Generated by the Mock Provider — not a real analysis."],
      });
    }

    const dataLimitationRefs = existingIds(catalog, ["data_quality.product_conversions", "data_quality.overall_status"]);
    const dataLimitations: GrowthReportAnalysis["dataLimitations"] = [
      {
        title: "Whacka product-side conversions are not connected",
        impact: "Signups, first-app-created, and app-published counts are unavailable, so downstream funnel stages cannot be measured yet.",
        relatedEvidenceRefs: dataLimitationRefs,
      },
    ];

    const signalsWorthReviewing: GrowthReportAnalysis["decisionInputs"]["signalsWorthReviewing"] = [];
    if (topChannelRefs.length > 0) {
      signalsWorthReviewing.push({
        signal: "Top-performing channel/content for the period",
        whyItMatters: "Identifying the strongest source/landing page combination is useful context for the next experiment decision.",
        evidenceRefs: topChannelRefs,
        confidence: "low",
      });
    }

    const questionRefs = existingIds(catalog, ["data_quality.overall_status"]);
    const questionsForDecisionAgent: GrowthReportAnalysis["decisionInputs"]["questionsForDecisionAgent"] = [
      {
        question: "Should Whacka product-conversion tracking be connected before prioritizing the next experiment?",
        reason: "Product-side conversion data is not connected yet, limiting how much of the funnel can currently be evaluated.",
        evidenceRefs: questionRefs.length > 0 ? questionRefs : existingIds(catalog, catalog.map((entry) => entry.id)).slice(0, 1),
      },
    ];

    const data: GrowthReportAnalysis = {
      executiveSummary: {
        headline: `Mock growth report for ${request.period.start} to ${request.period.end}`,
        summary:
          "This is a mock-generated executive summary produced without calling any LLM, for local end-to-end pipeline testing. " +
          "It references only evidence IDs present in the supplied catalog.",
        confidence: "low",
      },
      findings,
      funnelObservations,
      channelAndContentObservations,
      anomaliesOrNotableSignals: [],
      dataLimitations,
      decisionInputs: { signalsWorthReviewing, questionsForDecisionAgent },
    };

    return {
      data,
      provider: this.name,
      model: "mock-v0",
      requestId: null,
      stopReason: "end_turn",
      inputTokens: null,
      outputTokens: null,
    };
  }
}
