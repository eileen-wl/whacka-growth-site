import type { TopicScoringProvider } from "./topic-scoring-provider";
import type { Blocker, DimensionAssessment, TopicAssessment, TopicScoringAnalysis, TopicScoringContext, TopicScoringLLMRequest } from "../types/topic-scoring";
import type { LLMStructuredResult } from "../types/llm";

const MOCK_CAVEAT = "Generated by the Mock Provider — not a real analysis.";

function clamp(value: number, min: number, max: number): number {
  return Math.max(min, Math.min(max, value));
}

/** `relationshipToExistingContent.status` here uses TopicCandidate's public vocabulary (growth/contracts/topic-candidate.ts) — "related_to_existing_app"/"related_to_existing_topic"/"duplicate" all indicate observed overlap; only "new" doesn't. */
function overlapsExistingContent(context: TopicScoringContext): boolean {
  return context.relationshipToExistingContent.status !== "new";
}

function evidenceDimension(
  key: DimensionAssessment["key"],
  score: number,
  rationale: string,
  signalRefs: string[],
  sourceRecordRefs: string[] = []
): DimensionAssessment {
  return { key, score, scoreBasis: "evidence", rationale, signalRefs, sourceRecordRefs, limitations: [] };
}

function policyDefaultDimension(key: DimensionAssessment["key"], fallbackScore: number, limitation: string): DimensionAssessment {
  return { key, score: fallbackScore, scoreBasis: "policy_default", rationale: MOCK_CAVEAT, signalRefs: [], sourceRecordRefs: [], limitations: [limitation] };
}

function assessTopic(context: TopicScoringContext, fallbackScore: number): TopicAssessment {
  const allSignalIds = context.signals.map((signal) => signal.id);

  const demand = evidenceDimension(
    "demand",
    55,
    `${context.signals.length} supplied signal(s) reference this topic; ${MOCK_CAVEAT}`,
    allSignalIds
  );

  const audienceRelevance = evidenceDimension(
    "audience_relevance",
    55,
    `Target audience "${context.targetAudience}" was supplied for this topic; ${MOCK_CAVEAT}`,
    allSignalIds
  );

  const productFit =
    context.useCases.length > 0
      ? evidenceDimension("product_fit", 55, `${context.useCases.length} use case(s) were supplied for this topic; ${MOCK_CAVEAT}`, allSignalIds)
      : policyDefaultDimension("product_fit", fallbackScore, "No use cases were supplied for this topic.");

  const overlaps = overlapsExistingContent(context);
  const competition = overlaps
    ? evidenceDimension(
        "competition",
        30,
        `The topic's relationship to existing content is "${context.relationshipToExistingContent.status}", indicating observed overlap; ${MOCK_CAVEAT}`,
        allSignalIds
      )
    : policyDefaultDimension("competition", fallbackScore, "No competitor or content-overlap evidence beyond the campaign's own catalog was supplied.");

  const feasibility = policyDefaultDimension(
    "feasibility",
    fallbackScore,
    "Feasibility of implementation was not assessed from any supplied evidence in this run."
  );

  const noveltyScore = context.relationshipToExistingContent.status === "duplicate" ? 20 : overlaps ? 40 : 60;
  const novelty = evidenceDimension(
    "novelty",
    noveltyScore,
    `The topic's relationship to existing content is "${context.relationshipToExistingContent.status}"; ${MOCK_CAVEAT}`,
    allSignalIds
  );

  const evidenceStrengthScore = clamp(30 + context.signalCount * 15, 30, 75);
  const evidenceStrength = evidenceDimension(
    "evidence_strength",
    evidenceStrengthScore,
    `${context.signalCount} supporting signal(s) from ${context.sourceCount} source record(s); ${MOCK_CAVEAT}`,
    allSignalIds,
    context.citedSourceRecords.map((record) => record.id)
  );

  const blockers: Blocker[] = [];
  if (context.relationshipToExistingContent.status === "duplicate") {
    blockers.push({
      code: "duplicate_or_existing",
      description: `This topic's relationship to existing content is "duplicate"; ${MOCK_CAVEAT}`,
      signalRefs: allSignalIds,
      sourceRecordRefs: [],
    });
  }

  return {
    topicId: context.topicId,
    dimensions: [demand, audienceRelevance, productFit, competition, feasibility, novelty, evidenceStrength],
    confidence: "medium",
    blockers,
    reviewNotes: [MOCK_CAVEAT],
  };
}

/**
 * A fixed-logic (no LLM) implementation of TopicScoringProvider used for
 * local end-to-end testing without an API key or network access. It only
 * ever cites signal/source-record ids it finds in that specific topic's own
 * supplied context — never a value from another topic's context, and never
 * an invented ID. Uses conservative scores near 50 and `policy_default` for
 * anything it can't ground in real evidence (feasibility is always
 * policy-default here, since a mock has no real engineering-capacity
 * signal) — it must never simulate a confident market conclusion. Combined
 * with the deterministic engine's mock-source confidence cap, this
 * normally yields `needs_human_review` for current mock inputs, not
 * `advance`.
 */
export class MockTopicScoringProvider implements TopicScoringProvider {
  readonly name = "mock";

  async generateStructuredScores(request: TopicScoringLLMRequest): Promise<LLMStructuredResult<TopicScoringAnalysis>> {
    const fallbackScore = request.scoringProfile.insufficientEvidenceFallbackScore;

    const topicAssessments = request.topicContexts.map((context) => assessTopic(context, fallbackScore));

    const data: TopicScoringAnalysis = {
      topicAssessments,
      portfolioObservations: {
        topicCoverage: `${topicAssessments.length} of ${request.topicCatalog.length} supplied topics were assessed.`,
        evidenceCoverage: "Mock-generated placeholder coverage note for local pipeline validation, not a real analysis.",
        majorLimitations: [MOCK_CAVEAT, ...(request.sourceIsMock ? ["The source Signal Mining run was itself mock-generated."] : [])],
        requiresHumanReview: true,
      },
    };

    return {
      data,
      provider: this.name,
      model: "mock-v0",
      requestId: null,
      stopReason: "end_turn",
      inputTokens: null,
      outputTokens: null,
    };
  }
}
