import type { AssetGenerationProvider } from "./asset-generation-provider";
import type { AssetGenerationAnalysis, AssetGenerationLLMRequest } from "../types/asset-generation";
import type { LLMStructuredResult } from "../types/llm";

const MOCK_CAVEAT = "Generated by the Mock Provider — for engineering validation only, not real market copy.";

function truncate(value: string, maxLength: number): string {
  return value.length <= maxLength ? value : `${value.slice(0, maxLength - 1)}…`;
}

function toTitle(value: string): string {
  return value
    .split(/\s+/)
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}

/**
 * A fixed-logic (no LLM) implementation of AssetGenerationProvider used for
 * local end-to-end testing without an API key or network access. It only
 * ever builds content from the actual supplied context (the selected
 * topic's own problem statement, target audience, use cases, and desired
 * outcome) — never an invented metric, never a URL, never a publication
 * claim. Social posts are produced only for the explicitly requested
 * channels; zero requested channels yields zero posts. Every field is
 * clearly labeled as mock-generated so it can never be mistaken for
 * validated market copy.
 */
export class MockAssetGenerationProvider implements AssetGenerationProvider {
  readonly name = "mock";

  async generateStructuredAssets(request: AssetGenerationLLMRequest): Promise<LLMStructuredResult<AssetGenerationAnalysis>> {
    const { context } = request;
    const name = truncate(toTitle(context.canonicalName), 200);
    const primaryType: AssetGenerationAnalysis["cta"]["primaryType"] = request.allowedCtaTypes.includes("build") ? "build" : "copy_prompt";

    const useCases = context.useCases.length > 0 ? context.useCases : ["Use the mini app to address the stated problem."];
    const steps = useCases.slice(0, 10).map((useCase, index) => ({
      title: truncate(`Step ${index + 1}: ${useCase}`, 100),
      description: truncate(`Placeholder step description for engineering validation — covers "${useCase}". ${MOCK_CAVEAT}`, 380),
    }));

    const data: AssetGenerationAnalysis = {
      appConcept: {
        name,
        slugSuggestion: context.slug,
        category: "Mini App Concept",
        tagline: truncate(`A focused way to ${context.desiredOutcome}`, 200),
        shortDescription: truncate(`${context.problemStatement} ${MOCK_CAVEAT}`, 500),
        problem: truncate(context.problemStatement, 2000),
        solution: truncate(`${context.desiredOutcome} ${useCases.join(" ")} ${MOCK_CAVEAT}`, 2000),
        whoItsFor: [truncate(context.targetAudience, 300)],
        steps,
        appPrompt: truncate(
          `Build a mini app called ${name} for a small business. It should help with: ${useCases.join("; ")}. ` +
            `Goal: ${context.desiredOutcome}. ${MOCK_CAVEAT}`,
          4000
        ),
        creativeBrief: {
          hook: truncate(`Never worry about ${context.canonicalName.toLowerCase()} again.`, 300),
          persona: truncate(context.targetAudience, 300),
          scenario: truncate(context.problemStatement, 1000),
          assumptions: [truncate(`Assumes the underlying evidence for "${context.canonicalName}" reflects a real, recurring need. ${MOCK_CAVEAT}`, 440)],
          limitations: [truncate(MOCK_CAVEAT, 440)],
        },
      },
      seo: {
        title: truncate(`${name} — Mini App`, 200),
        metaDescription: truncate(`${context.desiredOutcome} ${MOCK_CAVEAT}`, 300),
        primaryKeyword: truncate(context.canonicalName.toLowerCase(), 160),
        secondaryKeywords: [],
        faq: [
          {
            question: "Do I need coding experience to build this?",
            answer: "No — Whacka lets you describe what you need in plain language and generates the working app for you.",
          },
        ],
      },
      cta: {
        primaryType,
        labels: {
          primary: truncate(`Build ${name} with Whacka`, 200),
          viewDemo: null,
          remix: null,
          build: primaryType === "build" ? truncate(`Build ${name} with Whacka`, 200) : null,
          copyPrompt: primaryType === "copy_prompt" ? truncate(`Copy the ${name} prompt`, 200) : null,
        },
        rationale: truncate(`"${primaryType}" was selected deterministically from the supplied allowed CTA types. ${MOCK_CAVEAT}`, 440),
      },
      socialPosts: request.requestedSocialChannels.map((channel) => ({
        channel,
        variant: "concept-announcement",
        copy: truncate(`Proposed concept: ${name}. ${context.desiredOutcome} ${MOCK_CAVEAT}`, 2000),
      })),
      generationNotes: {
        topicAlignment: truncate(`This concept directly addresses "${context.problemStatement}" as stated in the selected topic. ${MOCK_CAVEAT}`, 440),
        differentiationFromExistingApps: truncate(
          context.existingAppCatalog.length > 0
            ? `Checked against ${context.existingAppCatalog.length} existing app(s) in the supplied catalog; no exact name/slug match found. ${MOCK_CAVEAT}`
            : `No existing apps were supplied for comparison. ${MOCK_CAVEAT}`,
          440
        ),
        assumptions: [truncate(`Source Topic Scoring mock status: ${context.sourceScoringIsMock}. Source human-reviewed: ${context.sourceTopicsHumanReviewed}.`, 440)],
        limitations: [truncate(MOCK_CAVEAT, 440)],
        requiresHumanReview: true,
      },
    };

    return {
      data,
      provider: this.name,
      model: "mock-v0",
      requestId: null,
      stopReason: "end_turn",
      inputTokens: null,
      outputTokens: null,
    };
  }
}
