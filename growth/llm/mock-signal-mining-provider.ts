import { slugify } from "../lib/ids";
import type { SignalMiningProvider } from "./signal-mining-provider";
import type { SignalMiningAnalysis, SignalMiningLLMRequest, SignalProposal, SignalSourceRecord, TopicCluster } from "../types/signal-mining";
import type { LLMStructuredResult } from "../types/llm";

const MOCK_CAVEAT = "Generated by the Mock Provider — not a real analysis.";

function mapSignalType(record: SignalSourceRecord): SignalProposal["signalType"] {
  switch (record.source.type) {
    case "search_console":
      return "search_pattern";
    case "ga4":
    case "posthog":
      return "engagement_pattern";
    default:
      // mentor_input, user_feedback, manual, competitor_page, social_discussion,
      // keyword_source, product_request, research_note, other
      return "manual_input";
  }
}

function clusterKeyFor(record: SignalSourceRecord): string {
  if (record.entities.productsOrApps.length > 0) return `existing_app:${record.entities.productsOrApps[0]}`;
  if (record.source.type === "search_console") return "search_demand";
  if (record.source.type === "ga4" || record.source.type === "posthog") return "traffic_channels";
  return "manual_input";
}

function clusterLabel(key: string): string {
  if (key.startsWith("existing_app:")) return `Signals related to ${key.slice("existing_app:".length)}`;
  if (key === "search_demand") return "Search demand signals";
  if (key === "traffic_channels") return "Traffic channel signals";
  return "Manual input signals";
}

function truncate(value: string, maxLength: number): string {
  return value.length <= maxLength ? value : `${value.slice(0, maxLength - 1)}…`;
}

function dedupe(values: string[]): string[] {
  return [...new Set(values)];
}

/**
 * A fixed-logic (no LLM) implementation of SignalMiningProvider used for
 * local end-to-end testing without an API key or network access. It only
 * ever cites source-record ids it finds in the supplied catalog and app
 * slugs it finds in the supplied existing content catalog — never a
 * hardcoded value that might not exist for a given run's inputs.
 *
 * Deliberately does NOT turn `growth_loop_feedback`-sourced records into
 * signal proposals on their own — a feedback instruction is an
 * instruction/constraint, not measured demand evidence (see
 * growth/signal-sources/growth-loop-feedback-adapter.ts and
 * growth/README.md's "Mock feedback behavior" section) — so per section 11
 * of the Signal Mining spec, "collect_more_data feedback generates a topic
 * only when source records support it." Those records are reported in
 * `unresolvedSourceRecords` instead.
 */
export class MockSignalMiningProvider implements SignalMiningProvider {
  readonly name = "mock";

  async generateStructuredSignals(request: SignalMiningLLMRequest): Promise<LLMStructuredResult<SignalMiningAnalysis>> {
    const { sourceRecordCatalog, existingContentCatalog, feedbackContext } = request;
    const knownAppSlugs = new Set(existingContentCatalog.map((entry) => entry.appSlug));

    const signalProposals: SignalProposal[] = [];
    const unresolvedSourceRecords: SignalMiningAnalysis["unresolvedSourceRecords"] = [];
    const byClusterKey = new Map<string, { records: SignalSourceRecord[]; temporaryIds: string[] }>();

    let proposalIndex = 0;
    for (const record of sourceRecordCatalog) {
      if (record.source.type === "growth_loop_feedback") {
        unresolvedSourceRecords.push({
          sourceRecordRef: record.id,
          reason: "insufficient_evidence",
          note: "A Growth Loop Feedback instruction alone is not measured demand evidence; no corroborating source record was found for it in this run.",
        });
        continue;
      }

      proposalIndex += 1;
      const temporaryId = `proposed_signal_${proposalIndex}`;
      const limitations = [...record.quality.limitations, MOCK_CAVEAT];

      signalProposals.push({
        temporaryId,
        signalType: mapSignalType(record),
        title: record.title,
        summary: truncate(record.content, 600),
        evidenceExcerpt: truncate(record.content, 300),
        sourceRecordRefs: [record.id],
        entities: {
          keywords: record.entities.keywords,
          topics: record.entities.topics,
          audiences: record.entities.audiences,
          productsOrApps: record.entities.productsOrApps,
          channels: record.entities.channels,
        },
        quality: {
          confidence: record.quality.confidence,
          freshness: "unknown",
          limitations,
        },
      });

      const key = clusterKeyFor(record);
      const bucket = byClusterKey.get(key) ?? { records: [], temporaryIds: [] };
      bucket.records.push(record);
      bucket.temporaryIds.push(temporaryId);
      byClusterKey.set(key, bucket);
    }

    let clusterIndex = 0;
    const topicClusters: TopicCluster[] = [];
    for (const [key, bucket] of byClusterKey) {
      clusterIndex += 1;
      const canonicalName = clusterLabel(key);
      const keywords = dedupe(bucket.records.flatMap((r) => r.entities.keywords));
      const audiences = dedupe(bucket.records.flatMap((r) => r.entities.audiences));
      const useCases = dedupe(bucket.records.map((r) => r.title)).slice(0, 10);

      let relatedAppSlugs: string[] = [];
      let status: TopicCluster["relationshipToExistingContent"]["status"] = "unknown";
      if (key.startsWith("existing_app:")) {
        const slug = key.slice("existing_app:".length);
        if (knownAppSlugs.has(slug)) {
          relatedAppSlugs = [slug];
          status = "existing";
        }
      }

      topicClusters.push({
        temporaryId: `proposed_topic_${clusterIndex}`,
        canonicalName,
        slugSuggestion: slugify(canonicalName).replace(/_/g, "-"),
        aliases: [],
        problemStatement: `${bucket.records.length} supplied source record(s) point to activity in this area during ${request.period.start} to ${request.period.end}; this is a mock-generated placeholder problem statement, not a real analysis.`,
        targetAudience: audiences.length > 0 ? audiences : ["Mock Provider placeholder audience — not a real analysis."],
        useCases,
        desiredOutcome: "Mock-generated placeholder outcome for local pipeline validation, not a real analysis.",
        signalProposalRefs: bucket.temporaryIds,
        relationshipToExistingContent: { status, relatedAppSlugs },
        confidence: "low",
        limitations: [MOCK_CAVEAT, ...(keywords.length === 0 ? ["No keyword entities were present in the underlying source records."] : [])],
      });
    }

    const majorLimitations = [MOCK_CAVEAT];
    if (feedbackContext?.isMock) {
      majorLimitations.push("Supplied Growth Loop Feedback context was itself mock-generated — not a real strategic instruction.");
    }

    const data: SignalMiningAnalysis = {
      signalProposals,
      topicClusters,
      unresolvedSourceRecords,
      analysisNotes: {
        sourceCoverage: `${signalProposals.length} of ${sourceRecordCatalog.length} supplied source records were mapped to a proposed signal.`,
        majorLimitations,
        requiresHumanReview: true,
      },
    };

    return {
      data,
      provider: this.name,
      model: "mock-v0",
      requestId: null,
      stopReason: "end_turn",
      inputTokens: null,
      outputTokens: null,
    };
  }
}
