import type { ExperimentDecisionProvider } from "./experiment-decision-provider";
import type {
  ExperimentDecisionAnalysis,
  ExperimentDecisionContext,
  ExperimentDecisionLLMRequest,
  RankedExperimentOption,
  RecommendedExperiment,
} from "../types/experiment-decision";
import type { EvidenceEntry } from "../types/growth-report";
import type { LLMStructuredResult } from "../types/llm";

function findMeasurableEntry(catalog: EvidenceEntry[], ids: string[]): EvidenceEntry | undefined {
  for (const id of ids) {
    const entry = catalog.find((candidate) => candidate.id === id);
    if (entry && (entry.value === null || typeof entry.value === "number")) return entry;
  }
  return undefined;
}

const MOCK_CAVEAT = "Generated by the Mock Provider — not a real analysis.";

function buildDeferDecision(context: ExperimentDecisionContext, reason: string): ExperimentDecisionAnalysis {
  const limitationRefs = context.limitationCatalog.slice(0, 3).map((entry) => entry.id);
  const relatedRefs = limitationRefs.length > 0 ? limitationRefs : context.evidenceCatalog.slice(0, 1).map((entry) => entry.id);

  return {
    decisionSummary: {
      decisionStatus: "defer",
      headline: "Decision deferred — insufficient evidence for a confident recommendation",
      rationale: reason,
      confidence: "low",
      recommendedExperimentId: null,
    },
    rankedExperimentOptions: [],
    recommendedExperiment: null,
    deferDecision: {
      reason,
      missingEvidence: ["A non-mock Growth Report analysis with real findings and confidence levels for this period."],
      requiredNextObservations: [
        {
          observation:
            "Run the Growth Report Agent with a live (non-mock) provider for this period, then re-run the Experiment Decision Agent against that report.",
          relatedEvidenceOrLimitationRefs: relatedRefs,
        },
      ],
      earliestDecisionCondition: "As soon as a non-mock Growth Report is available for this period.",
    },
    rejectedOrDeferredOptions: [],
    handoff: {
      forNextLoop: [{ item: "Re-run the Growth Report Agent with a real provider once configured.", destination: "manual_review", reason }],
      humanReviewRequired: true,
    },
  };
}

function buildProceedOrDeferDecision(context: ExperimentDecisionContext): ExperimentDecisionAnalysis {
  const { decisionScope } = context;

  if (decisionScope.availableTopics.length === 0 || decisionScope.availableCtaTypes.length === 0) {
    return buildDeferDecision(
      context,
      "There isn't enough observed topic/app or CTA activity in this period's evidence to responsibly recommend a bounded experiment."
    );
  }

  const primaryMetricEntry = findMeasurableEntry(context.evidenceCatalog, ["behavior.event_based_cta_rate", "behavior.total_cta_clicks"]);
  if (!primaryMetricEntry) {
    return buildDeferDecision(context, "No suitable measurable evidence entry was found to serve as a primary metric for an experiment.");
  }
  const guardrailEntry = findMeasurableEntry(context.evidenceCatalog, ["traffic.sessions", "behavior.page_views"]);

  const topic = decisionScope.availableTopics[0];
  const ctaType = decisionScope.availableCtaTypes[0];

  const evidenceRefs = [primaryMetricEntry.id, ...(guardrailEntry ? [guardrailEntry.id] : [])];
  const guardrailMetricRefs = guardrailEntry ? [guardrailEntry.id] : [];
  const findingRefs = context.findingCatalog.slice(0, 1).map((entry) => entry.id);
  const limitationRefs = context.limitationCatalog.slice(0, 1).map((entry) => entry.id);
  const successCriterion = "Higher event-based CTA rate than the control during the same experiment window.";

  const option: RankedExperimentOption = {
    id: "experiment_1",
    rank: 1,
    lever: "cta",
    title: `Emphasize the ${ctaType} CTA for ${topic}`,
    target: { topicOrApp: topic, ctaType, channel: null },
    hypothesis: `A more prominent ${ctaType} CTA on ${topic} will increase the event-based CTA rate relative to the current control.`,
    proposedChange: `Increase the visual emphasis of the ${ctaType} CTA on the ${topic} app page.`,
    controlDescription: "Current CTA presentation, unchanged.",
    variantDescription: `${topic} page with a more prominent ${ctaType} CTA.`,
    measurementPlan: {
      primaryMetricRef: primaryMetricEntry.id,
      expectedDirection: "increase",
      successCriterion,
      guardrailMetricRefs,
      measurementCaveats: [MOCK_CAVEAT],
    },
    evidenceRefs,
    findingRefs,
    limitationRefs,
    confidence: "low",
    dependencies: [],
    risks: [MOCK_CAVEAT],
    whyNotHigherRanked: null,
  };

  const recommendedExperiment: RecommendedExperiment = {
    experimentId: option.id,
    objective: `Increase ${ctaType} engagement for ${topic} without reducing the selected traffic guardrail.`,
    hypothesis: option.hypothesis,
    implementationBrief: {
      change: option.proposedChange,
      unchangedElements: ["All other CTAs and page content remain unchanged."],
      targetPagesOrApps: [topic],
      targetCta: ctaType,
      targetChannel: null,
    },
    measurementPlan: {
      primaryMetricRef: primaryMetricEntry.id,
      secondaryMetricRefs: [],
      guardrailMetricRefs,
      successCriterion,
      failureCriterion: "No improvement in event-based CTA rate, or a decline in the guardrail metric.",
      minimumObservationRequirement:
        "Both control and variant must receive measurable pageviews and use the same tracking events before any comparison is made.",
      knownMeasurementLimitations: [MOCK_CAVEAT],
    },
    evidenceRefs,
    findingRefs,
    confidence: "low",
  };

  return {
    decisionSummary: {
      decisionStatus: "proceed",
      headline: `Mock-derived recommendation: emphasize ${ctaType} for ${topic}`,
      rationale: "This is a mock-generated, low-confidence recommendation for local pipeline validation, not a real strategic decision.",
      confidence: "low",
      recommendedExperimentId: option.id,
    },
    rankedExperimentOptions: [option],
    recommendedExperiment,
    deferDecision: null,
    rejectedOrDeferredOptions: [],
    handoff: {
      forNextLoop: [{ item: "Confirm this mock-derived recommendation before treating it as real.", destination: "manual_review", reason: MOCK_CAVEAT }],
      humanReviewRequired: true,
    },
  };
}

/**
 * A fixed-logic (no LLM) implementation of ExperimentDecisionProvider used
 * for local end-to-end testing without an API key or network access. It
 * only ever cites evidence/finding/limitation IDs and decision-scope
 * values it finds in the supplied context — never a hardcoded one that
 * might not exist for a given period. When the source Growth Report is
 * itself mock-generated (the common case today), it always defers, per
 * the rule that a mock report must never be presented as grounds for a
 * real strategic decision.
 */
export class MockExperimentDecisionProvider implements ExperimentDecisionProvider {
  readonly name = "mock";

  async generateStructuredDecision(request: ExperimentDecisionLLMRequest): Promise<LLMStructuredResult<ExperimentDecisionAnalysis>> {
    const { context } = request;

    const data = context.sourceReportIsMock
      ? buildDeferDecision(
          context,
          "The source Growth Report itself is mock-generated placeholder analysis, so no real strategic recommendation can be made from it."
        )
      : buildProceedOrDeferDecision(context);

    return {
      data,
      provider: this.name,
      model: "mock-v0",
      requestId: null,
      stopReason: "end_turn",
      inputTokens: null,
      outputTokens: null,
    };
  }
}
